type PixelIconName = keyof typeof pixelArt;

// Integer-aligned, filled pixels keep the artwork crisp without icon fonts or filters.
const iconPaths = Object.fromEntries(
  Object.entries(pixelArt).map(([name, rows]) => [
    name,
    rows.flatMap((row, y) => Array.from(row.matchAll(/1+/g), (match) =>
      `M${match.index} ${y}h${match[0].length}v1h-${match[0].length}z`,
    )).join(""),
  ]),
);

export function PixelIcon({ name, className = "" }: { name: PixelIconName; className?: string }) {
  return (
    <svg className={`pixel-icon ${className}`} viewBox="0 0 16 16" width="16" height="16" fill="currentColor" shapeRendering="crispEdges" aria-hidden="true" focusable="false">
      <path d={iconPaths[name]} />
    </svg>
  );
}

export function PlatformIcon({ platform, className }: { platform: string; className?: string }) {
  const name = platform === "macOS" || platform === "iOS" ? "apple"
    : platform === "Windows" ? "windows"
      : platform === "Linux" ? "linux"
        : platform === "Android" ? "android" : "download";

  return <PixelIcon name={name} className={className} />;
}
